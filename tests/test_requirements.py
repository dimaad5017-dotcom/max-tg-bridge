"""Список библиотек должен совпадать с тем, что мост на самом деле берёт.

aiohttp мост импортирует напрямую — вложения он качает сам, — а в списке его не было:
библиотека приезжала прицепом к aiogram. Пока aiogram её тянет, всё работает и заметить
нечего. Перестанет тянуть — мост не запустится, а по списку будет не понять почему:
того, чего в нём нет, никто и не ищет.

Проверка тут не ради чистоты, а ради установки на чужой машине: у себя всё уже стоит,
и недостающую строку у себя не увидишь никогда.
"""

import ast
import re
import sys
from importlib.metadata import packages_distributions
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СПИСОК = КОРЕНЬ / "requirements.txt"


def требования() -> list[str]:
    """Строки requirements.txt как есть, без комментариев и пустых."""
    строки = СПИСОК.read_text(encoding="utf-8").splitlines()
    return [строка.strip() for строка in строки if строка.strip() and not строка.startswith("#")]


def название(строка: str) -> str:
    """Имя пакета из строки требования: до первого знака сравнения или скобки."""
    return re.split(r"[<>=!~;\[]", строка, maxsplit=1)[0].strip().lower().replace("_", "-")


def импорты_моста() -> set[str]:
    """Что мост ввозит извне: только верхний уровень имени, только чужое."""
    найдено: set[str] = set()
    for файл in sorted((КОРЕНЬ / "bridge").glob("*.py")):
        for узел in ast.walk(ast.parse(файл.read_text(encoding="utf-8"))):
            if isinstance(узел, ast.Import):
                найдено.update(псевдоним.name.split(".")[0] for псевдоним in узел.names)
            # level > 0 — это «из соседнего файла», такое в список библиотек не идёт.
            elif isinstance(узел, ast.ImportFrom) and not узел.level and узел.module:
                найдено.add(узел.module.split(".")[0])
    return {имя for имя in найдено if имя not in sys.stdlib_module_names and имя != "bridge"}


class TestСписокБиблиотек:
    def test_всё_что_мост_импортирует_в_нём_объявлено(self):
        откуда = packages_distributions()
        объявлено = {название(строка) for строка in требования()}

        нехватка = {
            имя: пакеты
            for имя in импорты_моста()
            if (пакеты := откуда.get(имя))
            and not any(пакет.lower().replace("_", "-") in объявлено for пакет in пакеты)
        }

        assert not нехватка, f"мост импортирует, а в requirements.txt нет: {нехватка}"

    def test_у_каждой_строки_есть_верхняя_граница(self):
        """Без потолка установка однажды притащит следующую старшую версию.

        Она выйдет с переписанным API, мост упадёт прямо при импорте, и человек увидит
        только «мост падает сразу после запуска» — ни слова о том, что дело в обновлении,
        которого он не просил.
        """
        без_потолка = [строка for строка in требования() if "<" not in строка]

        assert not без_потолка, f"нечем ограничить сверху: {без_потолка}"

    def test_список_и_pyproject_говорят_одно_и_то_же(self):
        """Расхождение здесь не сломает мост сразу, но однажды поставит разные версии."""
        текст = (КОРЕНЬ / "pyproject.toml").read_text(encoding="utf-8")
        внутри = текст.split("dependencies = [", 1)[1].split("]", 1)[0]
        из_pyproject = {название(строка) for строка in re.findall(r'"([^"]+)"', внутри)}

        assert из_pyproject == {название(строка) for строка in требования()}
