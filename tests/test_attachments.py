"""Скачивание вложений: файл, о размере которого не предупредили.

Проверка размера смотрела на заголовок Content-Length и на этом успокаивалась. Но
называть размер заранее никто не обязан: отдают потоком, размер неизвестен — и
`or 0` превращал «не знаю» в «ноль байт», то есть в разрешение. Дальше мост читал
ответ целиком в память, и двухчасовое видео с утренника укладывало машину в своп.

Сервер здесь настоящий, пусть и на localhost. Подменять aiohttp нельзя: сломана была
как раз работа с ним, и на подделке проверка проверяла бы саму себя.
"""

import asyncio
from contextlib import suppress

import pytest
from aiohttp import web

from bridge import main

КУСОК = 64 * 1024


class Раздача:
    """Отдаёт заданное число байтов кусками. Про размер молчит, если не попросили."""

    def __init__(self, всего, объявлять=False, замереть=False):
        self.всего = всего
        self.объявлять = объявлять
        self.замереть = замереть
        self.отдано = 0

    async def отдать(self, request):
        response = web.StreamResponse()
        if self.объявлять:
            response.content_length = self.всего
        await response.prepare(request)

        if self.замереть:
            # Отдача встала после заголовков — так выглядит зависший сервер.
            await asyncio.sleep(5)

        # Мост вправе оборваться на полпути: он для того и переделан. Ругани в логе
        # теста от этого быть не должно.
        with suppress(Exception):
            while self.отдано < self.всего:
                сколько = min(КУСОК, self.всего - self.отдано)
                await response.write(b"x" * сколько)
                self.отдано += сколько
            await response.write_eof()
        return response


def скачать(раздача, срок=10, попыток=1):
    """По умолчанию одной попыткой: про размер и сроки повторы ничего не добавляют."""

    async def прогнать():
        app = web.Application()
        app.router.add_get("/file", раздача.отдать)
        # Уборка не ждёт обработчик: мост от него уже ушёл, а тест не должен
        # досиживать вместе с ним чужой sleep.
        runner = web.AppRunner(app, shutdown_timeout=0.1)
        await runner.setup()
        await web.TCPSite(runner, "127.0.0.1", 0).start()
        порт = runner.addresses[0][1]
        try:
            # Со сроком: без него тест на зависшую отдачу не падал бы, а висел, —
            # а висящий тест никто не читает, его просто убивают.
            return await asyncio.wait_for(
                main._download(f"http://127.0.0.1:{порт}/file", "video.mp4", tries=попыток),
                timeout=срок,
            )
        finally:
            await runner.cleanup()

    return asyncio.run(прогнать())


@pytest.fixture
def потолок(monkeypatch):
    """Полсотни мегабайт гонять по кругу в каждом тесте незачем — правило то же."""
    monkeypatch.setattr(main, "UPLOAD_LIMIT", 128 * 1024)
    return 128 * 1024


class TestРазмерВложения:
    def test_маленькое_скачивает_целиком(self, потолок):
        """Починка не должна испортить обычный случай — с ним мост и живёт каждый день."""
        раздача = Раздача(всего=100 * 1024)

        добыто = скачать(раздача)

        assert добыто.file is not None
        assert len(добыто.file.data) == 100 * 1024

    def test_объявленный_размер_отсекает_как_и_раньше(self, потолок):
        раздача = Раздача(всего=8 * 1024 * 1024, объявлять=True)

        добыто = скачать(раздача)

        assert добыто.file is None
        assert "не принимает" in добыто.problem

    def test_необъявленный_размер_тоже_отсекает(self, потолок):
        """Тот самый случай: размера в заголовке нет, и проверке нечего было читать."""
        раздача = Раздача(всего=8 * 1024 * 1024)

        добыто = скачать(раздача)

        assert добыто.file is None
        assert "не принимает" in добыто.problem

    def test_обрывает_на_месте_а_не_после(self, потолок):
        """Сказать про съеденную память, что её съели, — не защита, а отчёт о потерях."""
        раздача = Раздача(всего=8 * 1024 * 1024)

        скачать(раздача)

        assert раздача.отдано < 4 * 1024 * 1024

    def test_зависшую_отдачу_не_ждёт_вечно(self, monkeypatch):
        """Пять минут по умолчанию — треть всего бюджета догонялки на один битый файл."""
        monkeypatch.setattr(main, "DOWNLOAD_TIMEOUT", 0.3)
        раздача = Раздача(всего=1024, замереть=True)

        добыто = скачать(раздача, срок=5)

        assert добыто.file is None
        assert "не скачалось" in добыто.problem


class Капризная:
    """Сервер, который отказывает первые сколько-то раз, а потом отдаёт файл."""

    def __init__(self, отказов, код=503):
        self.отказов = отказов
        self.код = код
        self.запросов = 0

    async def отдать(self, request):
        self.запросов += 1
        if self.отказов:
            self.отказов -= 1
            return web.Response(status=self.код)
        return web.Response(body=b"x" * 1024)


@pytest.fixture
def без_пауз(monkeypatch):
    """Настоящие пять секунд ждать незачем: проверяем, что повторяет, а не сколько ждёт."""
    monkeypatch.setattr(main, "FIRST_FETCH_PAUSE", 0.01)


class TestСерверMAXНеОтветил:
    """Тот самый случай, из-за которого пропали две школьные фотографии.

    Сервер вложений MAX не отозвался на минуту. Мост сходил за фотографией один раз,
    написал в тему «не доставлено» — и на этом закончил. Строка ушла удачно, значит
    сообщение обработано: отмечено доставленным и прочитанным. Обычная догонялка
    ходит по непрочитанному, и к этому сообщению она уже не вернулась. Фотографии не
    стало нигде, кроме MAX, куда как раз и не заходят — ради чего мост и писался.

    Поэтому здесь разделяется «сервер молчит» и «сервер сказал нет». Первое проходит
    само, и просить надо снова. Второе не пройдёт никогда, и повторы — только задержка
    очереди: за фотографией в теме стоит текст, который ждать не должен.
    """

    def test_после_отказа_просит_ещё_раз(self, без_пауз):
        сервер = Капризная(отказов=2)

        добыто = скачать(сервер, попыток=main.FETCH_TRIES)

        assert добыто.file is not None, "сдался, хотя сервер ожил со второй попытки"
        assert сервер.запросов == 3

    def test_упрямый_отказ_не_держит_очередь_вечно(self, без_пауз):
        сервер = Капризная(отказов=99)

        добыто = скачать(сервер, попыток=main.FETCH_TRIES)

        assert добыто.file is None
        assert сервер.запросов == main.FETCH_TRIES

    def test_молчащий_сервер_повод_вернуться_позже(self, без_пауз):
        """Эта отметка и решает, догонит мост фотографию или похоронит её."""
        добыто = скачать(Капризная(отказов=99), попыток=main.FETCH_TRIES)

        assert добыто.again

    def test_такого_файла_нет_и_через_полчаса(self, без_пауз):
        """404 — это осмысленное «нет». Ни повторять, ни обещать догнать тут нечего."""
        сервер = Капризная(отказов=99, код=404)

        добыто = скачать(сервер, попыток=main.FETCH_TRIES)

        assert добыто.file is None
        assert сервер.запросов == 1, "долбил сервер отказом, который сам не пройдёт"
        assert not добыто.again
